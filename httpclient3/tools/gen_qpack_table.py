#!/usr/bin/env python3
"""Writes src/qpack_table.cee: QPACK's static table (RFC 9204, Appendix A).

The entries are read from a C# source that lists them as two arrays of `"..."u8.ToArray()` lines, names then
values, 99 each. Usage: gen_qpack_table.py <QpackStaticTable.cs>
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
items = re.findall(r'^\s*(?:"((?:[^"\\]|\\.)*)"u8\.ToArray\(\)|Array\.Empty<byte>\(\)),', text, re.M)
assert len(items) == 198, len(items)
names, values = items[:99], items[99:]
assert names[0] == ":authority" and values[0] == ""
assert (names[1], values[1]) == (":path", "/")
assert (names[17], values[17]) == (":method", "GET")
assert (names[25], values[25]) == (":status", "200")
assert (names[98], values[98]) == ("x-frame-options", "sameorigin")

out = ["// QPACK's static table (RFC 9204, Appendix A). Generated by tools/gen_qpack_table.py: do not edit.", ""]
out.append("/// How many entries the static table has: indexes 0 to 98.")
out.append("public const QPACK_STATIC_COUNT: usize = 99;")
out.append("")
for what, column in (("Name", names), ("Value", values)):
    out.append(f"/// Entry `i`'s {what.lower()}; empty past the table.")
    out.append(f"public fn qpackStatic{what}(i: usize) -> StringView => match (i) {{")
    for i, v in enumerate(column):
        if what == "Value" and v == "":
            continue
        out.append(f'    {i} => "{v}",')
    out.append('    _ => "",')
    out.append("};")
    out.append("")
open("src/qpack_table.cee", "w", encoding="utf-8").write("\n".join(out))
